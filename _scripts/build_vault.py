GEN_MARK = "# auto-generated by build_vault.py —— 本文件由脚本生成，重跑会覆盖"


def w(rel, text):
    p = os.path.join(VAULT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8") as f:
        f.write(text.rstrip() + "\n")
    return rel


def load_works(slug):
    p = os.path.join(DATA_DIR, slug + ".json")
    if not os.path.exists(p):
        return []
    try:
        return json.load(open(p, encoding="utf-8"))
    except Exception:
        return []


def swatch(hexcode):
    return ('<span style="display:inline-block;width:26px;height:14px;'
            'background:%s;border:1px solid #8888;border-radius:2px;'
            'vertical-align:-2px;margin-right:6px"></span>' % hexcode)


