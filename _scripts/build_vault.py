def movement_note(mv, works):
    slug = mv["slug"]
    lines = []
    A = lines.append
    A("---")
    A(GEN_MARK)
    A("type: 流派")
    A("流派: %s" % mv["name_zh"])
    A("英文: %s" % mv["name_en"])
    A("时期: %s" % mv["period"])
    A("地区: %s" % mv["region"])
    A("分类: %s" % mv["category"])
    A("图片授权: %s" % ("CC0 / 公共领域（自动抓取）" if works else "无可用 CC0 图，纯提示词卡"))
    A("配色: [%s]" % ", ".join('"%s"' % h for h, _ in mv["palette"]))
    A("标签:")
    A("  - 流派")
    A("  - %s" % mv["name_en"].lower().replace(" ", "-"))
    A("---")
    A("")
    A("# %s · %s" % (mv["name_zh"], mv["name_en"]))
    A("")
    A("> [!abstract] 一句话")
    A("> **%s**" % mv["one_liner"])
    A("")
    A("| 分类 | 时期 | 地区 | 代表艺术家 |")
    A("|---|---|---|---|")
    A("| %s | %s | %s | %s |" % (
        mv["category"], mv["period"], mv["region"],
        "、".join(a for a, _ in mv["artists"][:4])))
    A("")
    A("---")
    A("")
    # 一、核心主张
    A("## 一、核心主张")
    A("")
    for c in mv["core"]:
        A("- %s" % c)
    A("")
    # 二、视觉语言拆解
    A("## 二、视觉语言拆解")
    A("")
    A("> [!tip] 这一节是「看什么」。先看懂，再谈提示词。")
    A("")
    A("| 维度 | 拆解 |")
    A("|---|---|")
    for k, v in mv["visual"].items():
        A("| **%s** | %s |" % (k, v))
    A("")
    # 三、配色
    A("## 三、配色板")
    A("")
    for h, name in mv["palette"]:
        A("- %s `%s` **%s**" % (swatch(h), h, name))
    A("")
    A("> [!example] 配色提示词（直接粘）")
    A("> `%s`" % ", ".join("%s %s" % (n, h) for h, n in mv["palette"]))
    A("")
    # 四、提示词结构
    A("## 四、提示词结构")
    A("")
    A("> [!note] 六层拼装法")
    A("> `主体 + 风格 + 光照 + 色彩 + 构图 + 媒介 + 情绪 + 镜头`")
    A("> 下面每一层都可以单独拆出来复用——换主体不换风格层，就是你的风格迁移模板。")
    A("")
    A("| 层 | 可复用片段 |")
    A("|---|---|")
    order = [("style", "风格"), ("lighting", "光照"), ("color", "色彩"),
             ("composition", "构图"), ("medium", "媒介"), ("mood", "情绪"), ("camera", "镜头")]
    for key, label in order:
        A("| **%s** | `%s` |" % (label, mv["prompt"][key]))
    A("")
    A("### 整段正向提示词")
    A("")
    A("```text")
    A("%s" % build_positive(mv).strip())
    A("```")
    A("")
    A("> [!warning] 用法：这是**风格层**，不是完整提示词。")
    A("> 在前面接你自己的主体描述，例如：`<你的主体>, %s`" % mv["prompt"]["style"][:80])
    A("")
    A("### 负向提示词")
    A("")
    A("```text")
    A("%s" % mv["negative"].strip())
    A("```")
    A("")
    # 五、视频层
    A("## 五、AI 视频层")
    A("")
    A("> [!info] 文生视频 = 上面的静态描述 + 下面这三行")
    A("")
    A("| 层 | 内容 |")
    A("|---|---|")
    A("| **Motion 运动** | %s |" % mv["video"]["motion"])
    A("| **Camera 运镜** | %s |" % mv["video"]["camera"])
    A("")
    A("> [!important] 关键判断")
    A("> %s" % mv["video"]["note"])
    A("")
    # 六、代表作品
    A("## 六、代表作品（CC0 实图）")
    A("")
    if works:
        A("*全部来自开放授权数据源，图片与元数据均为 CC0 / 公共领域，可自由使用。*")
        A("")
        for i, wk in enumerate(works, 1):
            A("### %d. %s" % (i, wk["title"]))
            A("")
            if wk.get("local_image"):
                A("![[%s]]" % os.path.basename(wk["local_image"]))
                A("")
            meta = " · ".join(x for x in [wk.get("artist"), wk.get("date"), wk.get("medium")] if x)
            A("**%s**" % (meta or "—"))
            A("")
            A("来源：[%s](%s) · %s · [高清原图](%s)" % (
                wk["source"], wk.get("page_url") or "#", wk["license"], wk["image_url_hi"]))
            A("")
    else:
        A("> [!warning] 该流派暂无 CC0 可用图片")
        A("> 原因是这个流派的代表作品多在版权保护期内（例如 1930 年之后的现代作品）。")
        A("> 想找视觉参考，去 [WikiArt 该流派页面](https://www.wikiart.org/en/paintings-by-style) 看图，")
        A("> 但**不要把图下载进仓库再对外分享**——只存链接和提示词。")
        A("")
    # 七、翻车点
    A("## 七、常见翻车点")
    A("")
    for p in mv["pitfalls"]:
        A("- %s" % p)
    A("")
    # 八、关联
    A("## 八、关联流派")
    A("")
    for s in mv["see_also"]:
        tgt = next((m for m in MOVEMENTS if m["slug"] == s), None)
        A("- [[%s]]" % (tgt["name_zh"] if tgt else s))
    A("")
    A("---")
    A("")
    A("← [[流派总览]] · [[分类索引-%s]]　|　延伸阅读 [[提示词拆解方法]]" % mv["category"])
    return "\n".join(lines)



